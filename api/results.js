// 강사가 승인한 최종 첨삭 결과 저장 + 학생 링크로 조회
// 강사별로 데이터가 섞이지 않도록 모든 키를 t(강사 코드)로 구분해서 저장함
// 보안 (2026-09-25):
//  - 학생: 확인코드 조회(GET ?code=)와 결과 링크 조회(GET ?id=)만 공개
//  - 강사: 승인 저장(POST, 학생 이메일 발송 포함)·목록·기간 연장(PATCH)·삭제는 강사용 암호 필요
//  - 기간 만료 무시(admin=1)는 강사용 암호가 있을 때만 적용
import Redis from 'ioredis';
import { isStaff } from './_staff.js';

let redis;
function getRedis() {
  if (!redis) redis = new Redis(process.env.REDIS_URL);
  return redis;
}

function safeTeacherId(raw) {
  return String(raw || '').trim().toLowerCase().replace(/[^a-z0-9가-힣_-]/g, '').slice(0, 40);
}

function slugPart(s) {
  return String(s || '').trim().toLowerCase().replace(/[^a-z0-9가-힣]+/g, '-').slice(0, 40);
}

// 첨삭이 승인 완료될 때마다 트래커 진로모아관리 통계(기관·전공별 인원수)에 1명 누적 (내용은 저장 안 함)
async function upsertTrackerStat(client, t, orgName, field) {
  try {
    if (!orgName) return;
    const safeField = field || '(전공 미지정)';
    const id = `auto_resume_${slugPart(orgName)}_${slugPart(safeField)}`;
    const itemKey = `tracker_program:${t}:${id}`;
    const indexKey = `tracker_programs_index:${t}`;
    const now = new Date().toISOString();
    const raw = await client.get(itemKey);
    const record = raw ? JSON.parse(raw) : {
      id, orgName, field: safeField, programName: '자소서·이력서 첨삭 (자동집계)',
      date: now.slice(0, 10), participantCount: 0, renewalIntent: '미정',
      feedbackNotes: '', proposalNotes: '', avgSatisfaction: '', autoGenerated: true,
      createdAt: now
    };
    record.participantCount = (parseInt(record.participantCount, 10) || 0) + 1;
    record.updatedAt = now;
    await client.set(itemKey, JSON.stringify(record));
    await client.hset(indexKey, id, JSON.stringify({
      id: record.id, orgName: record.orgName, programName: record.programName,
      date: record.date, participantCount: record.participantCount, avgSatisfaction: record.avgSatisfaction
    }));
  } catch (err) {
    console.error('트래커 통계 자동 반영 실패:', err);
  }
}

function koDate(ms) {
  const d = new Date(ms + 9 * 60 * 60 * 1000); // 한국 시간 기준 날짜 표기
  return `${d.getUTCFullYear()}년 ${d.getUTCMonth() + 1}월 ${d.getUTCDate()}일`;
}

// 첨삭이 승인 완료되면, 학생이 이메일을 남겼을 경우에만 결과 링크를 자동으로 보내줌.
async function notifyStudentByEmail(t, id, item, host) {
  try {
    if (!process.env.RESEND_API_KEY) { console.error('학생 알림 건너뜀: RESEND_API_KEY 없음'); return; }
    const to = item.studentEmail;
    if (!to) { console.log('학생 알림 건너뜀: studentEmail 없음'); return; }
    const link = `https://${host}/?t=${encodeURIComponent(t)}#result=${id}`;
    const codePart = item.code
      ? `\n\n확인코드: ${item.code}\n(링크가 열리지 않으면 첨삭 앱의 "내 결과 확인"에서 이 코드로 조회할 수 있어요.)`
      : '';
    const expiryPart = item.expiresAt
      ? `\n\n조회 가능 기간: ${koDate(item.expiresAt - 1)}까지\n필요한 내용은 기간 안에 "워드로 저장"으로 받아두세요.`
      : '';
    const res = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${process.env.RESEND_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        from: 'MOA FORMULA <moaformula@jinromoa.co.kr>',
        to: [to],
        subject: `[자소서 첨삭] ${item.studentName || '학생'}님의 첨삭 결과가 도착했어요`,
        text: `${item.studentName || '학생'}님, 요청하신 자소서 첨삭 결과가 준비됐어요.\n\n아래 링크에서 확인해 주세요.\n${link}${codePart}${expiryPart}`
      })
    });
    if (!res.ok) {
      const body = await res.text();
      console.error('Resend 발송 실패(학생):', res.status, body);
    } else {
      console.log('Resend 발송 성공(학생):', to);
    }
  } catch (err) {
    console.error('학생 알림 메일 발송 실패:', err);
  }
}

// 이메일이 트래커 개인관리 카드와 일치하는 학생만 상담 이력에 자동 기록 (카드를 새로 만들지 않음)
async function upsertStudentConsultLog(client, t, studentEmail, kind) {
  try {
    const email = String(studentEmail || '').trim().toLowerCase();
    if (!email) return false;
    const indexKey = `tracker_students_index:${t}`;
    const hash = await client.hgetall(indexKey);
    let matchId = null;
    for (const [id, raw] of Object.entries(hash || {})) {
      try {
        const summary = JSON.parse(raw);
        if ((summary.email || '').trim().toLowerCase() === email) { matchId = id; break; }
      } catch (e) { /* 손상된 항목은 건너뜀 */ }
    }
    if (!matchId) return false;

    const itemKey = `tracker_student:${t}:${matchId}`;
    const raw = await client.get(itemKey);
    if (!raw) return false;
    const record = JSON.parse(raw);
    record.consultLog = record.consultLog || [];
    const today = new Date().toISOString().slice(0, 10);
    let todayEntry = record.consultLog.find(c => c.date === today && c.autoCounts);
    if (!todayEntry) {
      todayEntry = { date: today, memo: '', autoCounts: {}, auto: true };
      record.consultLog.push(todayEntry);
    }
    todayEntry.autoCounts[kind] = (todayEntry.autoCounts[kind] || 0) + 1;
    const labels = { resume: '자소서 첨삭', interview: '모의면접' };
    todayEntry.memo = Object.entries(todayEntry.autoCounts)
      .map(([k, n]) => `${labels[k] || k} ${n}건`)
      .join(' · ') + ' 완료 (자동 기록)';
    await client.set(itemKey, JSON.stringify(record));
    return true;
  } catch (err) {
    console.error('학생 상담이력 자동기록 실패:', err);
    return false;
  }
}

export default async function handler(req, res) {
  const client = getRedis();
  const t = safeTeacherId(req.query.t);
  if (!t) return res.status(400).json({ error: 't(강사 코드) 파라미터가 필요합니다.' });

  const indexKey = `resume_results_index:${t}`;
  const itemKey = (id) => `resume_result:${t}:${id}`;

  let staff = false;
  try { staff = await isStaff(req, client); } catch (err) { console.error(err); }
  const denied = () => res.status(401).json({ error: '강사용 암호가 필요합니다.' });

  if (req.method === 'POST') {
    if (!staff) return denied();
    const id = 'res_' + Date.now() + '_' + Math.random().toString(36).slice(2, 8);
    const item = { id, teacherId: t, ...req.body, approvedAt: Date.now() };

    let institutionNameForSurvey = null;
    let groupCodeExpiryDays = 5;
    try {
      const configRaw = await client.get(`resume_app_config:${t}`);
      const config = configRaw ? JSON.parse(configRaw) : null;
      const orgName = (item.studentInstitution && item.studentInstitution.trim()) || (config && config.institutionName) || null;
      if (orgName) {
        institutionNameForSurvey = orgName;
        item.trackerProgramId = `auto_resume_${slugPart(orgName)}_${slugPart(item.presetName || '(전공 미지정)')}`;
      }
      if (config && config.groupCodeExpiryDays) groupCodeExpiryDays = parseInt(config.groupCodeExpiryDays, 10) || 5;
    } catch (err) {
      console.error('트래커 연동용 설정 조회 실패:', err);
    }

    const isIndividualCoaching = await upsertStudentConsultLog(client, t, item.studentEmail, 'resume');
    if (!isIndividualCoaching) {
      const approvedDate = new Date(item.approvedAt);
      item.expiresAt = new Date(approvedDate.getFullYear(), approvedDate.getMonth(), approvedDate.getDate() + groupCodeExpiryDays).getTime();
    }

    await client.set(itemKey(id), JSON.stringify(item));

    const indexRaw = await client.get(indexKey);
    const index = indexRaw ? JSON.parse(indexRaw) : [];
    index.push({ id, code: item.code || '', studentName: item.studentName || '', presetName: item.presetName || '기본', itemCount: (item.items || []).length, docType: item.docType || 'resume', approvedAt: item.approvedAt, expiresAt: item.expiresAt || null });
    await client.set(indexKey, JSON.stringify(index));

    await notifyStudentByEmail(t, id, item, req.headers.host); // 서버리스 환경에서는 응답 전에 완료를 기다려야 중간에 끊기지 않음

    if (institutionNameForSurvey) {
      upsertTrackerStat(client, t, institutionNameForSurvey, item.presetName);
    }

    return res.status(200).json({ ok: true, id });
  }

  // 강사가 특정 학생 결과의 조회 기간을 연장함 (days일 뒤까지, 0이면 기간 제한 없음)
  if (req.method === 'PATCH') {
    if (!staff) return denied();
    const { id } = req.query;
    if (!id) return res.status(400).json({ error: 'id 파라미터가 필요합니다.' });
    const body = typeof req.body === 'string' ? JSON.parse(req.body || '{}') : (req.body || {});
    const days = Math.max(0, Math.min(365, parseInt(body.days, 10) || 0));
    const raw = await client.get(itemKey(id));
    if (!raw) return res.status(404).json({ error: '결과를 찾을 수 없습니다.' });
    const item = JSON.parse(raw);
    let expiresAt = null;
    if (days > 0) {
      const now = new Date();
      expiresAt = new Date(now.getFullYear(), now.getMonth(), now.getDate() + days).getTime();
    }
    item.expiresAt = expiresAt;
    item.extendedAt = Date.now();
    await client.set(itemKey(id), JSON.stringify(item));
    const indexRaw = await client.get(indexKey);
    const index = indexRaw ? JSON.parse(indexRaw) : [];
    const idx = index.findIndex(x => x.id === id);
    if (idx >= 0) { index[idx].expiresAt = expiresAt; await client.set(indexKey, JSON.stringify(index)); }
    return res.status(200).json({ ok: true, expiresAt });
  }

  if (req.method === 'GET') {
    const { id, list, code } = req.query;

    // 학생: 확인코드로 결과 조회
    if (code) {
      const indexRaw = await client.get(indexKey);
      const index = indexRaw ? JSON.parse(indexRaw) : [];
      const match = index.find(it => it.code === String(code).toUpperCase());
      if (!match) return res.status(404).json({ error: '해당 코드의 결과를 찾을 수 없습니다.' });
      if (match.expiresAt && Date.now() > match.expiresAt) return res.status(410).json({ error: '조회 가능한 기간이 지났어요. 결과가 필요하시면 강사님께 문의해 주세요.', expired: true });
      const raw = await client.get(itemKey(match.id));
      if (!raw) return res.status(404).json({ error: '결과를 찾을 수 없습니다.' });
      return res.status(200).json({ item: JSON.parse(raw) });
    }

    // 강사: 완료 목록
    if (list) {
      if (!staff) return denied();
      const indexRaw = await client.get(indexKey);
      const index = indexRaw ? JSON.parse(indexRaw) : [];
      return res.status(200).json({ items: index.reverse() });
    }

    // 학생·강사: 결과 링크 조회
    if (id) {
      const raw = await client.get(itemKey(id));
      if (!raw) return res.status(404).json({ error: '결과를 찾을 수 없습니다.' });
      const parsed = JSON.parse(raw);
      const adminView = req.query.admin === '1' && staff;
      if (!adminView && parsed.expiresAt && Date.now() > parsed.expiresAt) {
        return res.status(410).json({ error: '조회 가능한 기간이 지났어요. 결과가 필요하시면 강사님께 문의해 주세요.', expired: true });
      }
      return res.status(200).json({ item: parsed });
    }

    return res.status(400).json({ error: 'id 또는 list 파라미터가 필요합니다.' });
  }

  if (req.method === 'DELETE') {
    if (!staff) return denied();
    const { id } = req.query;
    if (!id) return res.status(400).json({ error: 'id 파라미터가 필요합니다.' });
    await client.del(itemKey(id));
    const indexRaw = await client.get(indexKey);
    const index = indexRaw ? JSON.parse(indexRaw) : [];
    await client.set(indexKey, JSON.stringify(index.filter(x => x.id !== id)));
    return res.status(200).json({ ok: true });
  }

  return res.status(405).json({ error: '허용되지 않는 요청입니다.' });
}
